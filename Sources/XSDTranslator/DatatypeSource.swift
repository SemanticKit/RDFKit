import Foundation

/// The Swift of the XSD datatypes RDF uses: for each, a value type, which
/// conforms to `XSD.SimpleType` (or `XSD.PrimitiveDatatype`), and the Swift
/// class that stands for the datatype as a class, an `rdfs:Datatype`.
///
/// - The value type is named by the datatype's name: `xsd:long` is `long`.
///   Its `base` is the Swift type of the definition's base, and its `facets`
///   are the facets of the definitions from its primitive down to it, as the
///   schema documents give them.
/// - The class is named as `RDFTranslatorPlugin` and `@Ontology` name the
///   Swift class of a class, `longIndividual`, and its `Member` is the value
///   type, so `Range(XSD.long)` in the DSL types a property `[XSD.long]`.
/// - `datatypes` lists the value types, in the order of RDF 1.2 Concepts
///   §5.1.
struct DatatypeSource {
    let documents: [String]
    let vocabulary: FacetVocabulary
    let compatible: CompatibleDatatypes
    let definitions: [String: SimpleTypeDefinition]

    /// The base of the primitive datatypes, which has no Swift type.
    static let atomicBase = "anyAtomicType"

    func render() throws -> String {
        guard compatible.namespace.hasPrefix(vocabulary.namespace) else {
            throw TranslationError(description: "the xsd namespace of RDF 1.2 Concepts, \(compatible.namespace), is not the XML Schema namespace \(vocabulary.namespace)")
        }
        var source = """
            // Generated by XSDTranslator from \(documents.joined(separator: ", ")).
            // Edit the documents and build again; this file is rewritten on every build.

            import RDFCore

            /// The namespace of the XML Schema datatypes, \(compatible.namespace), which the
            /// declared keys of the datatypes refer to.
            struct Namespace: RDFCore::Vocabulary {
                static let namespace = \(literal(compatible.namespace))
            }

            """
        for name in compatible.names {
            guard let definition = definitions[name] else {
                throw TranslationError(description: "RDF 1.2 Concepts lists xsd:\(name), which no schema document defines")
            }
            source += "\n" + (try valueType(definition))
            source += "\n" + classType(definition)
        }
        source += """

            /// The XML Schema datatypes RDF 1.2 Concepts §5.1 lists, "the RDF-compatible XSD types",
            /// in its order.
            public let datatypes: [any XSD::SimpleType.Type] = [
            """
        source += compatible.names.map { "\n    \(identifier($0)).self," }.joined()
        source += "\n]\n"
        return source
    }

    /// The definitions from the primitive down to `definition`.
    private func chain(_ definition: SimpleTypeDefinition) throws -> [SimpleTypeDefinition] {
        var chain = [definition]
        while chain[0].base != Self.atomicBase {
            guard let base = definitions[chain[0].base], compatible.names.contains(base.name) else {
                throw TranslationError(description: "xsd:\(chain[0].name) is derived from xsd:\(chain[0].base), which is not translated")
            }
            chain.insert(base, at: 0)
        }
        return chain
    }

    private func valueType(_ definition: SimpleTypeDefinition) throws -> String {
        let chain = try chain(definition)
        let primitive = chain[0]
        let isPrimitive = chain.count == 1
        let name = identifier(definition.name)
        var text = documentation(definition)
        text += "public struct \(name): XSD::\(isPrimitive ? "PrimitiveDatatype" : "SimpleType") {\n"
        text += "    public typealias Primitive = \(identifier(primitive.name))\n\n"
        text += "    /// The declared key of the datatype, from which an encoder derives its IRI.\n"
        text += "    public static let datatype = RDFCore::TermKey(\(literal(definition.name)), in: Namespace.self)\n\n"
        if !isPrimitive {
            text += "    public static let base: (any XSD::SimpleType.Type)? = \(identifier(definition.base)).self\n\n"
        }
        text += "    public static let facets: [XSD::Facet] = [\(try chain.flatMap(facets).map { "\n        \($0)," }.joined())\(chain.allSatisfy(\.facets.isEmpty) ? "" : "\n    ")]\n\n"
        text += "    public let value: \(identifier(primitive.name)).Value\n\n"
        text += "    /// The value of a lexical form in the datatype's lexical space.\n"
        text += "    public init(lexicalForm: Swift::String) throws(RDFCore::DatatypeError) {\n"
        text += "        value = try Self.value(lexicalForm: lexicalForm)\n    }\n\n"
        text += "    /// The value, when it is in the datatype's value space.\n"
        text += "    public init(_ value: \(identifier(primitive.name)).Value) throws(RDFCore::DatatypeError) {\n"
        text += "        self.value = try Self.checked(value)\n    }\n"
        return text + "}\n"
    }

    private func classType(_ definition: SimpleTypeDefinition) -> String {
        let name = identifier(definition.name)
        return """
            /// The datatype `xsd:\(definition.name)` as a class, an `rdfs:Datatype`: what a description
            /// writes in object position (`rdfs:range xsd:\(definition.name)`), and the class whose
            /// members, the values of ``\(definition.name)``, a property ranging over it holds.
            public final class \(identifier(definition.name + "Individual")): RDFCore::ResourceClass {
                public static let classKey: RDFCore::TermKey? = \(name).datatype

                /// A member of the class as a property value: a value of the datatype.
                public typealias Member = \(name)

                /// The datatype's members are values, never individuals.
                private init() {}

                public static func encodeDescription(to encoder: any Swift::Encoder) throws {
                    _ = encoder.container(keyedBy: RDFCore::PropertyKey.self)
                }

                public func encode(to encoder: any Swift::Encoder) throws {}
            }

            """
    }

    /// The facets one definition gives, as `XSD.Facet` expressions. The
    /// facets that may be given several times in one derivation step are
    /// grouped into one, which any of them satisfies.
    private func facets(_ definition: SimpleTypeDefinition) throws -> [String] {
        var expressions: [String] = []
        var groups: [String: [String]] = [:]
        var groupOrder: [String] = []
        for facet in definition.facets {
            switch vocabulary.facets[facet.name] {
            case .number:
                guard let number = Int(facet.value), number >= 0 else {
                    throw TranslationError(description: "xsd:\(definition.name): \(facet.name) is not a nonnegative integer")
                }
                expressions.append(".\(facet.name)(\(number))")
            case .keyword(let keywords):
                guard keywords.contains(facet.value) else {
                    throw TranslationError(description: "xsd:\(definition.name): \(facet.value) is not a value of \(facet.name)")
                }
                expressions.append(".\(facet.name)(.\(facet.value))")
            case .alternatives:
                if groups[facet.name] == nil { groupOrder.append(facet.name) }
                // A pattern's value is a regular expression (§4.3.4).
                groups[facet.name, default: []].append(facet.name == "pattern" ? "XSD::Pattern(\(literal(facet.value)))" : literal(facet.value))
            case .literal:
                expressions.append(".\(facet.name)(\(literal(facet.value)))")
            case .assertion, nil:
                throw TranslationError(description: "xsd:\(definition.name): \(facet.name) has no Swift translation")
            }
        }
        for name in groupOrder {
            expressions.append(".\(name)([\(groups[name]!.joined(separator: ", "))])")
        }
        return expressions
    }

    private func documentation(_ definition: SimpleTypeDefinition) -> String {
        var lines = ["The XML Schema datatype `xsd:\(definition.name)`"
            + (definition.source.map { " (<\($0)>)" } ?? "")
            + (definition.base == Self.atomicBase ? ", a primitive datatype." : ", derived by restriction from ``\(definition.base)``.")]
        let text = definition.documentation.split(separator: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        if !text.isEmpty { lines += [""] + text }
        return lines.map { $0.isEmpty ? "///\n" : "/// \($0)\n" }.joined()
    }

    private func identifier(_ name: String) -> String {
        "`" + name + "`"
    }

    private func literal(_ text: String) -> String {
        var literal = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\"": literal += "\\\""
            case "\\": literal += "\\\\"
            case "\n": literal += "\\n"
            case "\r": literal += "\\r"
            case "\t": literal += "\\t"
            default: literal.unicodeScalars.append(scalar)
            }
        }
        return literal + "\""
    }
}
