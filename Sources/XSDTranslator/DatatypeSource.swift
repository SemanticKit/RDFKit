import Foundation
import SwiftSyntax
import SwiftSyntaxBuilder
import TranslatorSyntax
import XSDDefinitions

/// The Swift of the XSD datatypes RDF uses, as swift-syntax declarations:
/// for each, a value type, which conforms to `XSD.PrimitiveDatatype` or
/// `XSD.DerivedDatatype`, and the Swift class that stands for the datatype as
/// a class, an `rdfs:Datatype`.
///
/// - The value type is named by the datatype's name: `xsd:long` is `long`.
///   A derived datatype's `Base` is the Swift type of its definition's base,
///   so the hierarchy is the type system's, and its `facets` are those its
///   own definition gives, as the schema documents give them.
/// - Its `denotation(inDerivationsOf:)` reads a literal of the datatype, or
///   of a datatype derived from it in one step or more: the translated
///   definitions give each datatype the ones derived from it.
/// - The class is named as `RDFTranslatorPlugin` and `@Ontology` name the
///   Swift class of a class, `longIndividual`, and its `Member` is the value
///   type, so `Range(XSD.long)` in the DSL types a property `[XSD.long]`.
struct DatatypeSource {
    let definitions: DatatypeDefinitions

    /// The module the declarations are in, whose protocols they conform to.
    static let module = "XSD"

    func render() throws -> String {
        var declarations: [DeclSyntax] = [DeclSyntax(namespace)]
        for definition in definitions.datatypes {
            declarations.append(DeclSyntax(try valueType(definition)))
            declarations.append(DeclSyntax(classType(definition)))
        }
        var items = [CodeBlockItemSyntax(item: .decl(DeclSyntax(ImportDeclSyntax(
            leadingTrivia: Trivia(pieces: [
                .lineComment("// Generated by XSDTranslator from \(definitions.documents.joined(separator: ", "))."), .newlines(1),
                .lineComment("// Edit the documents and build again; this file is rewritten on every build."), .newlines(2),
            ]),
            path: ImportPathComponentListSyntax([ImportPathComponentSyntax(name: .identifier("RDFCore"))])
        ))))]
        items += declarations.map { CodeBlockItemSyntax(leadingTrivia: .newlines(2), item: .decl($0)) }
        return SourceFileSyntax(statements: CodeBlockItemListSyntax(items)).formatted().description + "\n"
    }

    /// The namespace the declared keys of the datatypes refer to.
    private var namespace: StructDeclSyntax {
        StructDeclSyntax(
            leadingTrivia: .documentation([
                "The namespace of the XML Schema datatypes, \(definitions.namespace), which the",
                "declared keys of the datatypes refer to.",
            ]),
            name: .identifier("Namespace"),
            inheritanceClause: .of(.named(.identifier("Vocabulary"), in: "RDFCore")),
            memberBlock: MemberBlockSyntax(members: [
                MemberBlockItemSyntax(decl: VariableDeclSyntax(
                    modifiers: .of(.static),
                    .let,
                    name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("namespace"))),
                    initializer: InitializerClauseSyntax(value: ExprSyntax.string(definitions.namespace))
                )),
            ])
        )
    }

    private func valueType(_ definition: SimpleTypeDefinition) throws -> StructDeclSyntax {
        let chain = definitions.chain(to: definition)
        let primitive = chain[0]
        guard primitive.base == DatatypeDefinitions.atomicBase else {
            throw TranslationError(description: "xsd:\(definition.name) is derived from xsd:\(primitive.base), which is not translated")
        }
        let isPrimitive = chain.count == 1
        let name = TokenSyntax.escaped(definition.name)
        let primitiveType = TypeSyntax.named(.escaped(primitive.name))
        let valueSpace = TypeSyntax.member("Value", of: primitiveType)
        let literalForm = TypeSyntax.named(.identifier("LiteralForm"), in: "RDFCore")
        let datatypeError = TypeSyntax.named(.identifier("DatatypeError"), in: "RDFCore")
        let denotation = TypeSyntax.optional(.tuple([("value", valueSpace), ("literalForm", literalForm)]))

        var members: [(documentation: [String], decl: DeclSyntax)] = []
        members.append(([], DeclSyntax(TypeAliasDeclSyntax(
            modifiers: .of(.public),
            name: .identifier("Primitive"),
            initializer: TypeInitializerClauseSyntax(value: primitiveType)
        ))))
        if !isPrimitive {
            members.append((["The datatype this one is derived from by restriction."], DeclSyntax(TypeAliasDeclSyntax(
                modifiers: .of(.public),
                name: .identifier("Base"),
                initializer: TypeInitializerClauseSyntax(value: TypeSyntax.named(.escaped(definition.base)))
            ))))
        }
        members.append((["The declared key of the datatype, from which an encoder derives its IRI."], DeclSyntax(VariableDeclSyntax(
            modifiers: .of(.public, .static),
            .let,
            name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("datatype"))),
            initializer: InitializerClauseSyntax(value: ExprSyntax.call(.reference(.identifier("TermKey"), in: "RDFCore"), [
                (nil, .string(definition.name)),
                ("in", .member(.keyword(.self), of: .reference(.identifier("Namespace")))),
            ]))
        ))))
        members.append((["The constraining facets the datatype's definition gives."], DeclSyntax(VariableDeclSyntax(
            modifiers: .of(.public, .static),
            .let,
            name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("facets"))),
            type: TypeAnnotationSyntax(type: TypeSyntax.array(of: .named(.identifier("Facet"), in: Self.module))),
            initializer: InitializerClauseSyntax(value: ExprSyntax.array(try facets(definition)))
        ))))
        members.append((["The value."], DeclSyntax(VariableDeclSyntax(
            modifiers: .of(.public),
            .let,
            name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("value"))),
            type: TypeAnnotationSyntax(type: valueSpace)
        ))))
        members.append(([
            "The lexical form and datatype an encoder writes the value with: those of",
            "the literal it was decoded from, else its canonical form and this datatype.",
        ], DeclSyntax(VariableDeclSyntax(
            modifiers: .of(.public),
            .let,
            name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("literalForm"))),
            type: TypeAnnotationSyntax(type: literalForm)
        ))))

        let value = ExprSyntax.reference(.identifier("value"))
        let canonical = ExprSyntax.call(.member(.identifier("canonicalLiteralForm"), of: .selfType), [("of", value)])
        members.append((["The value of a lexical form in the datatype's lexical space."], DeclSyntax(InitializerDeclSyntax(
            modifiers: .of(.public),
            signature: FunctionSignatureSyntax(
                parameterClause: .of([("lexicalForm", "lexicalForm", .named(.identifier("String"), in: "Swift"))]),
                effectSpecifiers: .throwing(datatypeError)
            ),
            body: .of([
                .expr(.assignment(value, .try(.call(.member(.identifier("value"), of: .selfType), [("lexicalForm", .reference(.identifier("lexicalForm")))])))),
                .expr(.assignment(.reference(.identifier("literalForm")), canonical)),
            ])
        ))))
        members.append((["The value, when it is in the datatype's value space."], DeclSyntax(InitializerDeclSyntax(
            modifiers: .of(.public),
            signature: FunctionSignatureSyntax(
                parameterClause: .of([(nil, "value", valueSpace)]),
                effectSpecifiers: .throwing(datatypeError)
            ),
            body: .of([
                .expr(.assignment(.member(.identifier("value"), of: .selfValue), .try(.call(.member(.identifier("checked"), of: .selfType), [(nil, value)])))),
                .expr(.assignment(.reference(.identifier("literalForm")), canonical)),
            ])
        ))))

        let literal = ExprSyntax.reference(.identifier("literal"))
        let found = ExprSyntax.reference(.identifier("denotation"))
        members.append(([
            "The value a literal denotes in the datatype's value space, written as the",
            "literal is: a literal of this datatype, of one it is derived from or of one",
            "derived from it, that is well-typed and whose value satisfies this datatype's",
            "facets.",
        ], DeclSyntax(InitializerDeclSyntax(
            modifiers: .of(.public),
            optionalMark: .postfixQuestionMarkToken(),
            signature: FunctionSignatureSyntax(parameterClause: .of([(nil, "literal", .named(.identifier("Literal"), in: "RDFCore"))])),
            body: .of([
                .stmt(StmtSyntax(GuardStmtSyntax(
                    conditions: ConditionElementListSyntax([ConditionElementSyntax(condition: .optionalBinding(OptionalBindingConditionSyntax(
                        bindingSpecifier: .keyword(.let),
                        pattern: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("denotation"))),
                        initializer: InitializerClauseSyntax(value: ExprSyntax.call(.member(.identifier("denotation"), of: .selfType), [("of", literal)]))
                    )))]),
                    body: .of([.stmt(StmtSyntax(ReturnStmtSyntax(expression: NilLiteralExprSyntax())))])
                ))),
                .expr(.assignment(value, .member(.identifier("value"), of: found))),
                .expr(.assignment(.reference(.identifier("literalForm")), .member(.identifier("literalForm"), of: found))),
            ])
        ))))

        // This datatype's own literals, then those of each datatype derived
        // from it in one step, which search their own derivations.
        var search = ExprSyntax.call(.member(.identifier("ownDenotation"), of: .selfType), [("of", literal)])
        for derivation in definitions.derivations(of: definition) {
            let next = ExprSyntax.call(.member(.identifier("denotation"), of: .reference(.escaped(derivation.name))), [("inDerivationsOf", literal)])
            search = .coalescing(search, next)
        }
        let derivations = definitions.derivations(of: definition).map { "``\($0.name)``" }
        members.append((derivations.isEmpty ? [
            "The value a literal of this datatype denotes, and the form it is written in.",
            "No datatype RDF uses is derived from this one.",
        ] : [
            "The value a literal of this datatype, or of one derived from it, denotes in",
            "its own datatype, and the form it is written in. Derived from this datatype",
            "in one step: \(derivations.joined(separator: ", ")).",
        ], DeclSyntax(FunctionDeclSyntax(
            modifiers: .of(.public, .static),
            name: .identifier("denotation"),
            signature: FunctionSignatureSyntax(
                parameterClause: .of([("inDerivationsOf", "literal", .named(.identifier("Literal"), in: "RDFCore"))]),
                returnClause: ReturnClauseSyntax(type: denotation)
            ),
            body: .of([.expr(search)])
        ))))

        return StructDeclSyntax(
            leadingTrivia: .documentation(documentation(definition)),
            modifiers: .of(.public),
            name: name,
            inheritanceClause: .of(.named(.identifier(isPrimitive ? "PrimitiveDatatype" : "DerivedDatatype"), in: Self.module)),
            memberBlock: memberBlock(members)
        )
    }

    private func classType(_ definition: SimpleTypeDefinition) -> ClassDeclSyntax {
        let valueType = TypeSyntax.named(.escaped(definition.name))
        let encoder = TypeSyntax.existential(.named(.identifier("Encoder"), in: "Swift"))
        return ClassDeclSyntax(
            leadingTrivia: .documentation([
                "The datatype `xsd:\(definition.name)` as a class, an `rdfs:Datatype`: what a description",
                "writes in object position (`rdfs:range xsd:\(definition.name)`), and the class whose",
                "members, the values of ``\(definition.name)``, a property ranging over it holds.",
            ]),
            modifiers: .of(.public, .final),
            name: .escaped(definition.name + "Individual"),
            inheritanceClause: .of(.named(.identifier("ResourceClass"), in: "RDFCore")),
            memberBlock: memberBlock([
                ([], DeclSyntax(VariableDeclSyntax(
                    modifiers: .of(.public, .static),
                    .let,
                    name: PatternSyntax(IdentifierPatternSyntax(identifier: .identifier("classKey"))),
                    type: TypeAnnotationSyntax(type: TypeSyntax.optional(.named(.identifier("TermKey"), in: "RDFCore"))),
                    initializer: InitializerClauseSyntax(value: ExprSyntax.member(.identifier("datatype"), of: .reference(.escaped(definition.name))))
                ))),
                (["A member of the class as a property value: a value of the datatype."], DeclSyntax(TypeAliasDeclSyntax(
                    modifiers: .of(.public),
                    name: .identifier("Member"),
                    initializer: TypeInitializerClauseSyntax(value: valueType)
                ))),
                (["The datatype's members are values, never individuals."], DeclSyntax(InitializerDeclSyntax(
                    modifiers: .of(.private),
                    signature: FunctionSignatureSyntax(parameterClause: .of([])),
                    body: .of([])
                ))),
                ([], DeclSyntax(FunctionDeclSyntax(
                    modifiers: .of(.public, .static),
                    name: .identifier("encodeDescription"),
                    signature: FunctionSignatureSyntax(parameterClause: .of([("to", "encoder", encoder)]), effectSpecifiers: .throwing()),
                    body: .of([.expr(.assignment(
                        ExprSyntax(DiscardAssignmentExprSyntax()),
                        .call(.member(.identifier("container"), of: .reference(.identifier("encoder"))), [
                            ("keyedBy", .member(.keyword(.self), of: .reference(.identifier("PropertyKey"), in: "RDFCore"))),
                        ])
                    ))])
                ))),
                ([], DeclSyntax(FunctionDeclSyntax(
                    modifiers: .of(.public),
                    name: .identifier("encode"),
                    signature: FunctionSignatureSyntax(parameterClause: .of([("to", "encoder", encoder)]), effectSpecifiers: .throwing()),
                    body: .of([])
                ))),
            ])
        )
    }

    /// The member block of `members`, each with its documentation and a
    /// blank line before it.
    private func memberBlock(_ members: [(documentation: [String], decl: DeclSyntax)]) -> MemberBlockSyntax {
        MemberBlockSyntax(members: MemberBlockItemListSyntax(members.enumerated().map { index, member in
            let space: Trivia = index == 0 ? [] : .newlines(2)
            return MemberBlockItemSyntax(decl: member.decl.with(\.leadingTrivia, space + .documentation(member.documentation)))
        }))
    }

    /// The facets the definition gives, as `XSD.Facet` expressions. The
    /// facets that may be given several times in one derivation step are
    /// grouped into one, which any of them satisfies.
    private func facets(_ definition: SimpleTypeDefinition) throws -> [ExprSyntax] {
        var expressions: [ExprSyntax] = []
        var groups: [(name: String, values: [ExprSyntax])] = []
        for facet in definition.facets {
            let name = TokenSyntax.identifier(facet.name)
            switch definitions.vocabulary.facets[facet.name] {
            case .number:
                guard let number = Int(facet.value), number >= 0 else {
                    throw TranslationError(description: "xsd:\(definition.name): \(facet.name) is not a nonnegative integer")
                }
                expressions.append(.call(.member(name, of: nil), [(nil, ExprSyntax(IntegerLiteralExprSyntax(number)))]))
            case .keyword(let keywords):
                guard keywords.contains(facet.value) else {
                    throw TranslationError(description: "xsd:\(definition.name): \(facet.value) is not a value of \(facet.name)")
                }
                expressions.append(.call(.member(name, of: nil), [(nil, .member(.identifier(facet.value), of: nil))]))
            case .alternatives:
                // A pattern's value is a regular expression (§4.3.4).
                let value: ExprSyntax = facet.name == "pattern"
                    ? .call(.reference(.identifier("Pattern"), in: Self.module), [(nil, .string(facet.value))])
                    : .string(facet.value)
                if let index = groups.firstIndex(where: { $0.name == facet.name }) {
                    groups[index].values.append(value)
                } else {
                    groups.append((facet.name, [value]))
                }
            case .literal:
                expressions.append(.call(.member(name, of: nil), [(nil, .string(facet.value))]))
            case .assertion, nil:
                throw TranslationError(description: "xsd:\(definition.name): \(facet.name) has no Swift translation")
            }
        }
        for group in groups {
            expressions.append(.call(.member(.identifier(group.name), of: nil), [(nil, .array(group.values))]))
        }
        return expressions
    }

    private func documentation(_ definition: SimpleTypeDefinition) -> [String] {
        var lines = ["The XML Schema datatype `xsd:\(definition.name)`"
            + (definition.source.map { " (<\($0)>)" } ?? "")
            + (definition.base == DatatypeDefinitions.atomicBase ? ", a primitive datatype." : ", derived by restriction from ``\(definition.base)``.")]
        let text = definition.documentation.split(separator: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
        if !text.isEmpty { lines += [""] + text }
        return lines
    }
}
