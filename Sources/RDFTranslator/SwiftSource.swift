import Foundation
import IRIKit
import RDFCore
import SwiftBasicFormat
import SwiftSyntax
import SwiftSyntaxBuilder

/// The Swift source of one module: the things its documents describe.
///
/// See ``Declarations`` for what each resource becomes. Besides them:
///
/// - `rdfs:label` and `rdfs:comment` are the declarations' documentation,
///   and `owl:deprecated true` is `@available(*, deprecated)`.
/// - Each individual's values are set once, the first time any individual
///   of the module is read, since individuals refer to each other, cycles
///   included (`:alice foaf:knows :bob . :bob foaf:knows :alice .`).
/// - A property's term type writes what the documents state about the
///   property, as a class's Swift class writes its class's description; a
///   property is never a module-level value.
/// - `ontology` is every description the documents give, the way back to
///   RDF.
/// - Every declaration of another module, and every public one of this
///   module, is named with a module selector (SE-0491), `RDF::Property`,
///   which looks only in that module. A module may name a resource like a
///   module it imports: the entailment regimes' `ent:RDF` is the constant
///   `RDF` in a module that imports `RDF`, and would hide that module from
///   `RDF.Property`.
///
/// The generated Swift keeps every individual's values in its
/// ``RDFCore/IndividualStorage``, the storage `@Ontology` uses too, so a
/// translated individual and one declared in the DSL are the same kind of
/// ``RDFCore/Resource``.
///
/// The source is a `SourceFileSyntax` built from SwiftSyntax's typed nodes
/// and written out formatted.
struct SwiftSource: DeclarationScope {
    let layer: Layer
    let vocabulary: Vocabulary
    let declarations: Declarations
    let below: [Declarations]
    let lower: Lower

    /// The nodes whose Swift is `@available(*, deprecated)`.
    private var deprecations = Deprecations()

    init(layer: Layer, vocabulary: Vocabulary, declarations: Declarations, below: [Declarations]) {
        self.layer = layer
        self.vocabulary = vocabulary
        self.declarations = declarations
        self.below = below
        self.lower = Lower(below)
        self.deprecations = Deprecations(self, vocabulary)
    }

    /// The module's Swift, formatted.
    func render() -> String {
        file().formatted().description
    }

    /// The module's Swift as a syntax tree.
    func file() -> SourceFileSyntax {
        let sources = layer.documents.isEmpty ? "no documents" : layer.documents.joined(separator: ", ")
        var items: [Item] = []
        let imports = ["IRIKit", "RDFCore"] + below.map(\.module)
        for (index, module) in imports.enumerated() {
            let header: Trivia = index > 0 ? [] : [
                .lineComment("// Generated by RDFTranslator from \(sources)."), .newlines(1),
                .lineComment("// Edit the RDF and build again; this file is rewritten on every build."), .newlines(2),
            ]
            items.append(Item(.tight, DeclSyntax(ImportDeclSyntax(
                leadingTrivia: header,
                path: ImportPathComponentListSyntax([ImportPathComponentSyntax(name: .swift(module))])
            ))))
        }
        items += namespaceTypes().map { Item(.spaced, $0) }

        for node in declarations.order {
            if let declaration = declarations.classes[node] {
                items += [classProtocol(declaration), storingProtocol(declaration), individualClass(of: declaration)].map { Item(.spaced, $0) }
            }
            if let property = declarations.properties[node] {
                items += ([propertyTerm(property), propertyValue(property)] + propertyStoring(property)).map { Item(.spaced, $0) }
            }
        }
        // A combination class is generated only for the blank nodes that
        // are its instances; a named individual's own class conforms to the
        // same storing protocols instead.
        let instantiated = Set(declarations.order.compactMap { node -> Int? in
            guard node.iri == nil, case .combination(let index)? = declarations.individuals[node]?.instanceOf else { return nil }
            return index
        })
        for (index, combination) in declarations.combinations.enumerated() where instantiated.contains(index) {
            items.append(Item(.spaced, combinationClass(combination)))
        }

        // The individuals, each an instance of its class, and the values the
        // documents give them. A named individual is the one instance of a
        // Swift class of its own, which carries its declared key.
        for node in declarations.order {
            guard let individual = declarations.individuals[node], node.iri != nil else { continue }
            items.append(Item(.spaced, namedIndividualClass(node, individual)))
        }
        var first = true
        for node in declarations.order {
            guard let individual = declarations.individuals[node] else { continue }
            let type = node.iri == nil ? classReference(individual.instanceOf) : .local(namedIndividualClassName(node))
            items.append(Item(first ? .spaced : .tight, DeclSyntax(VariableDeclSyntax(
                attributes: deprecation(node),
                modifiers: .access(false),
                .let,
                .swift(handle(node)),
                value: type.expression.called
            ))))
            first = false
        }
        for node in declarations.order {
            guard let individual = declarations.individuals[node], individual.isPublic else { continue }
            items.append(Item(.spaced, DeclSyntax(VariableDeclSyntax(
                leadingTrivia: documentation(node),
                attributes: deprecation(node),
                modifiers: .public,
                .let,
                .swift(individual.name),
                type: publicType(individual.publicType),
                value: ExprSyntax.closure([
                    .expr(ExprSyntax.discard.assigned(ExprSyntax.named("described"))),
                    .stmt(StmtSyntax(ReturnStmtSyntax(expression: ExprSyntax.named(handle(node))))),
                ]).called
            ))))
        }

        // `rdf:type` is the property every member of `rdfs:Resource` writes
        // its classes with, so the module that declares `rdfs:Resource`
        // gives it to the class's storing protocol.
        if let resource = declarations.classes[.iri(.rdfsResource)], let type = propertyDeclaration(.iri(.rdfType)) {
            items.append(Item(.spaced, DeclSyntax(ExtensionDeclSyntax(
                leadingTrivia: .documentation(["`rdf:type`, the property a member of `rdfs:Resource` writes its classes with."]),
                extendedType: resource.storingReference.type,
                memberBlock: MemberBlockSyntax([
                    DeclSyntax(VariableDeclSyntax(
                        modifiers: .publicStatic,
                        .var,
                        .identifier("typeProperty"),
                        type: TypeSyntax(OptionalTypeSyntax(wrappedType: SwiftReference.rdfCore("TermKey").type)),
                        accessors: .getter(type.termReference.expression.member("key"))
                    )),
                ])
            ))))
        }

        for (index, node) in declarations.additions.enumerated() {
            items.append(Item(.spaced, addition(node, index: index)))
        }

        items += self.documents().map { Item(.spaced, $0) }

        return SourceFileSyntax(
            statements: CodeBlockItemListSyntax(items.enumerated().map { index, item in
                let decl = index == 0 || item.spacing == .tight ? item.decl : item.decl.with(\.leadingTrivia, .newlines(2) + item.decl.leadingTrivia)
                return CodeBlockItemSyntax(item: .decl(decl))
            }),
            endOfFileToken: .endOfFileToken(leadingTrivia: .newline)
        )
    }

    /// The values the documents give the individuals and the descriptions
    /// they give, which name every declaration of the module, deprecated
    /// ones included. Swift warns where a declaration that is not deprecated
    /// names a deprecated one, so they are named in deprecated members of a
    /// private type, and `described` and `ontology` reach those members
    /// through the requirements of a protocol, which are not deprecated.
    private func documents() -> [DeclSyntax] {
        let what = "what the documents state"
        let documents = "the documents"
        let void = SwiftReference.swift("Void").type
        let descriptions = TypeSyntax.array(.any(SwiftReference.rdfCore("Description").type))
        // `(`the documents`.self as any `what the documents state`.Type)`
        let witness = ExprSyntax(TupleExprSyntax(elements: LabeledExprListSyntax([LabeledExprSyntax(
            expression: ExprSyntax.named(documents).dotSelf.as(.any(.metatype(SwiftReference.local(what).type)))
        )])))

        var assignments: [CodeBlockItemSyntax.Item] = []
        for node in declarations.order where declarations.individuals[node] != nil {
            for (property, objects) in values(of: node) {
                let declaration = propertyDeclaration(property)!
                assignments.append(.expr(ExprSyntax.named(handle(node)).member(declaration.member)
                    .assigned(ExprSyntax.array(objects.map { expression($0, as: declaration.kind) }))))
            }
        }
        let subjects = Set(layer.graph.map(\.subject))
        var entries: [ExprSyntax] = []
        for node in declarations.order where subjects.contains(node) {
            if let declaration = declarations.classes[node] {
                entries.append(SwiftReference.rdfCore("ClassDescription").expression.call(LabeledExprSyntax(expression: declaration.classReference.expression.dotSelf)))
            } else if let property = declarations.properties[node] {
                entries.append(property.termReference.expression.called)
            } else {
                entries.append(.named(handle(node)))
            }
        }
        entries += declarations.additions.indices.map { ExprSyntax.named(additionName($0)).called }
        let describers = layer.documents.isEmpty ? "this module's documents" : layer.documents.joined(separator: " and ")
        return [
            DeclSyntax(ProtocolDeclSyntax(
                leadingTrivia: .documentation(["What the documents give the individuals and the descriptions they give."]),
                modifiers: .access(false),
                name: .swift(what),
                memberBlock: MemberBlockSyntax(spaced: [
                    DeclSyntax(VariableDeclSyntax(
                        leadingTrivia: .documentation(["Sets the values the documents give the individuals, once."]),
                        modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                        .var,
                        .identifier("described"),
                        type: void,
                        accessors: .get
                    )),
                    DeclSyntax(VariableDeclSyntax(
                        leadingTrivia: .documentation(["The descriptions the documents give."]),
                        modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                        .var,
                        .identifier("ontology"),
                        type: descriptions,
                        accessors: .get
                    )),
                ])
            )),
            DeclSyntax(StructDeclSyntax(
                leadingTrivia: .documentation(["Names every declaration of the module, deprecated ones included, without a warning."]),
                modifiers: .access(false),
                name: .swift(documents),
                inheritanceClause: InheritanceClauseSyntax([SwiftReference.local(what).type]),
                memberBlock: MemberBlockSyntax(spaced: [
                    DeclSyntax(VariableDeclSyntax(
                        attributes: .deprecated,
                        modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                        .let,
                        .identifier("described"),
                        type: void,
                        value: ExprSyntax.closure(assignments).called
                    )),
                    DeclSyntax(VariableDeclSyntax(
                        attributes: .deprecated,
                        modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                        .var,
                        .identifier("ontology"),
                        type: descriptions,
                        accessors: .getter(ExprSyntax.list(entries))
                    )),
                ])
            )),
            DeclSyntax(VariableDeclSyntax(
                leadingTrivia: .documentation(["Sets the values the documents give the individuals, once."]),
                modifiers: .access(false),
                .let,
                .identifier("described"),
                type: void,
                value: witness.member("described")
            )),
            DeclSyntax(VariableDeclSyntax(
                leadingTrivia: .documentation([
                    "The descriptions \(describers) give\(layer.documents.count == 1 ? "s" : "").",
                    "",
                    "Encoding them gives back the documents' graph:",
                    "",
                    "    let document = try NTriplesEncoder().encode(ontology)",
                ]),
                modifiers: .public,
                .let,
                .identifier("ontology"),
                type: descriptions,
                value: ExprSyntax.closure([
                    .expr(ExprSyntax.discard.assigned(ExprSyntax.named("described"))),
                    .stmt(StmtSyntax(ReturnStmtSyntax(expression: witness.member("ontology")))),
                ]).called
            )),
        ]
    }

    /// A top-level declaration, and whether a blank line comes before it.
    private struct Item {
        enum Spacing { case spaced, tight }
        let spacing: Spacing
        let decl: DeclSyntax

        init(_ spacing: Spacing, _ decl: DeclSyntax) {
            self.spacing = spacing
            self.decl = decl
        }
    }

    // MARK: - Classes

    private func classProtocol(_ declaration: ClassDeclaration) -> DeclSyntax {
        let refined = (declarations.refinements[declaration.node] ?? []).compactMap(classDeclaration).map(\.protocolReference.type)
        let requirements = (declarations.requirements[declaration.node] ?? []).compactMap(propertyDeclaration).map { requirement in
            DeclSyntax(VariableDeclSyntax(
                leadingTrivia: documentation(requirement.node),
                attributes: deprecation(requirement.node),
                .var,
                .swift(requirement.member),
                type: type(of: requirement.kind),
                accessors: .getSet
            ))
        }
        return DeclSyntax(ProtocolDeclSyntax(
            leadingTrivia: documentation(declaration.node),
            attributes: deprecation(declaration.node),
            modifiers: .access(declaration.isPublic),
            name: .swift(declaration.protocolName),
            inheritanceClause: InheritanceClauseSyntax(refined.isEmpty ? [SwiftReference.rdfCore("Resource").type] : refined),
            memberBlock: MemberBlockSyntax(requirements)
        ))
    }

    /// The storing protocol of a class, which gives a member of the class
    /// every property it can have, each through its own storing protocol.
    private func storingProtocol(_ declaration: ClassDeclaration) -> DeclSyntax {
        let refined = [declaration.protocolReference.type] + declaration.storing.map(reference)
        let documentation = declaration.isPublic
            ? "A member of ``\(declaration.protocolName)`` that keeps its property values in an ``RDFCore/IndividualStorage``."
            : "A member of the class that keeps its property values in an ``RDFCore/IndividualStorage``."
        return DeclSyntax(ProtocolDeclSyntax(
            leadingTrivia: .documentation([documentation]),
            attributes: deprecation(declaration.node),
            modifiers: .access(declaration.isPublic),
            name: .swift(declaration.storingName),
            inheritanceClause: InheritanceClauseSyntax(refined),
            memberBlock: MemberBlockSyntax([])
        ))
    }

    /// The final class whose instances are the members of an RDF class. Its
    /// type is the class itself, a resource, so it writes the class's
    /// description too.
    private func individualClass(of declaration: ClassDeclaration) -> DeclSyntax {
        let properties = declaration.stored.sorted(by: SubjectTerm.inIRIOrder).compactMap(propertyDeclaration).map { $0.valueReference.expression.dotSelf }
        let members: [DeclSyntax] = [
            DeclSyntax(VariableDeclSyntax(
                modifiers: .publicStatic,
                .let,
                .identifier("classKey"),
                type: TypeSyntax(OptionalTypeSyntax(wrappedType: SwiftReference.rdfCore("TermKey").type)),
                value: key(declaration.node)
            )),
            DeclSyntax(TypeAliasDeclSyntax(
                leadingTrivia: .documentation(["A member of the class as a property value."]),
                modifiers: .public,
                name: .identifier("Member"),
                initializer: TypeInitializerClauseSyntax(value: memberType(of: declaration.member))
            )),
            DeclSyntax(VariableDeclSyntax(
                leadingTrivia: .documentation(["The properties a member of the class has, which a decoder reads."]),
                modifiers: .publicStatic,
                .let,
                .identifier("properties"),
                type: .array(.any(.metatype(.parenthesized(.composition([
                    SwiftReference.rdfCore("PropertyValue").type,
                    SwiftReference.swift("Decodable").type,
                ]))))),
                value: .array(properties)
            )),
        ] + individual(stated: [declaration.node]) + [
            encodeFunction(named: "encodeDescription", modifiers: .publicStatic, body: description(of: declaration.node)),
        ]
        return DeclSyntax(ClassDeclSyntax(
            leadingTrivia: documentation(declaration.node),
            attributes: deprecation(declaration.node),
            modifiers: DeclModifierListSyntax.access(declaration.isPublic).final,
            name: .swift(declaration.className),
            inheritanceClause: InheritanceClauseSyntax([
                declaration.storingReference.type,
                SwiftReference.rdfCore("ResourceClass").type,
                SwiftReference.rdfCore("DecodableResource").type,
            ]),
            memberBlock: MemberBlockSyntax(spaced: members)
        ))
    }

    private func combinationClass(_ combination: Combination) -> DeclSyntax {
        let conformances = combination.storing.map(reference) + [SwiftReference.rdfCore("PropertyValueStoring").type]
        return DeclSyntax(ClassDeclSyntax(
            leadingTrivia: .documentation([
                "An individual that is a member of \(combination.stated.isEmpty ? "no stated class" : "several classes"), or has properties its class's members cannot have.",
            ]),
            attributes: Deprecations.attributes(deprecations.contains(combination)),
            modifiers: DeclModifierListSyntax.access(false).final,
            name: .swift(combination.name),
            inheritanceClause: InheritanceClauseSyntax(conformances),
            memberBlock: MemberBlockSyntax(spaced: individual(stated: combination.stated))
        ))
    }

    /// The Swift class of a named individual, whose one instance is the
    /// individual, and whose declared key names it at the boundary.
    private func namedIndividualClass(_ node: SubjectTerm, _ declaration: IndividualDeclaration) -> DeclSyntax {
        let stated: [SubjectTerm]
        let conformances: [TypeSyntax]
        switch declaration.instanceOf {
        case .class(let type):
            stated = [type]
            conformances = [classDeclaration(type)!.storingReference.type]
        case .combination(let index):
            let combination = declarations.combinations[index]
            stated = combination.stated
            conformances = combination.storing.map(reference) + [SwiftReference.rdfCore("PropertyValueStoring").type]
        }
        return DeclSyntax(ClassDeclSyntax(
            leadingTrivia: .documentation(["The class of \(node.iri!.rawValue), a named individual."]),
            attributes: deprecation(node),
            modifiers: DeclModifierListSyntax.access(false).final,
            name: .swift(namedIndividualClassName(node)),
            inheritanceClause: InheritanceClauseSyntax(conformances),
            memberBlock: MemberBlockSyntax(spaced: [
                DeclSyntax(VariableDeclSyntax(
                    modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                    .let,
                    .identifier("key"),
                    type: TypeSyntax(OptionalTypeSyntax(wrappedType: SwiftReference.rdfCore("TermKey").type)),
                    value: key(node)
                )),
            ] + individual(stated: stated))
        ))
    }

    private func namedIndividualClassName(_ node: SubjectTerm) -> String {
        "resource \(declarations.order.firstIndex(of: node)!) Individual"
    }

    // MARK: - Keys

    /// The namespaces of the IRIs this module declares, and of the
    /// predicates its documents use that no module declares as a property,
    /// each a ``RDFCore/Vocabulary`` that the declared keys refer to. Two
    /// namespaces are one only when their Unicode scalars are the same:
    /// Swift's `==` on `String` would make a precomposed `é` and `e` with
    /// U+0301 one namespace, and so give two IRIs one key.
    private var namespaces: [String] {
        var namespaces: [String] = []
        let undeclared = layer.graph.map { SubjectTerm.iri($0.predicate) }.filter { propertyDeclaration($0) == nil }
        for node in declarations.order + undeclared {
            guard let namespace = node.iri?.namespace else { continue }
            if namespaces.firstIndex(ofScalars: namespace) == nil { namespaces.append(namespace) }
        }
        return namespaces
    }

    private func namespaceTypes() -> [DeclSyntax] {
        namespaces.enumerated().map { index, namespace in
            DeclSyntax(StructDeclSyntax(
                leadingTrivia: .documentation(["The namespace \(namespace), which declared keys of this module refer to."]),
                modifiers: .access(false),
                name: .swift(namespaceName(index)),
                inheritanceClause: InheritanceClauseSyntax([SwiftReference.rdfCore("Vocabulary").type]),
                memberBlock: MemberBlockSyntax([
                    DeclSyntax(VariableDeclSyntax(
                        modifiers: [DeclModifierSyntax(name: .keyword(.static))],
                        .let,
                        .identifier("namespace"),
                        value: .string(namespace)
                    )),
                ])
            ))
        }
    }

    private func namespaceName(_ index: Int) -> String {
        "namespace \(index)"
    }

    /// The declared key of a node: its local name in its namespace, or `nil`
    /// for a blank node.
    private func key(_ node: SubjectTerm) -> ExprSyntax {
        guard let iri = node.iri else { return .nil }
        let index = namespaces.firstIndex(ofScalars: iri.namespace)!
        return SwiftReference.rdfCore("TermKey").expression.call(
            LabeledExprSyntax(expression: ExprSyntax.string(iri.localName)),
            LabeledExprSyntax("in", ExprSyntax.named(namespaceName(index)).dotSelf)
        )
    }

    /// The classes and the storage of a generated class. Its
    /// `Encodable` conformance comes from ``RDFCore/PropertyValueStoring``,
    /// which writes the classes as `rdf:type`.
    private func individual(stated: [SubjectTerm]) -> [DeclSyntax] {
        let types = stated.compactMap(classDeclaration).map { $0.classReference.expression.dotSelf }
        return [
            DeclSyntax(VariableDeclSyntax(
                modifiers: .publicStatic,
                .let,
                .identifier("classes"),
                type: .array(.any(.metatype(SwiftReference.rdfCore("ResourceClass").type))),
                value: .array(types)
            )),
            DeclSyntax(VariableDeclSyntax(
                modifiers: .public,
                .let,
                .identifier("storage"),
                value: SwiftReference.rdfCore("IndividualStorage").expression.called
            )),
            initializer(documentation: ["An individual no declaration names: a blank node at the boundary."]),
        ]
    }

    /// `public init() {}`, documented.
    private func initializer(documentation: [String]) -> DeclSyntax {
        DeclSyntax(InitializerDeclSyntax(
            leadingTrivia: .documentation(documentation),
            modifiers: .public,
            signature: FunctionSignatureSyntax(parameterClause: FunctionParameterClauseSyntax([])),
            body: CodeBlockSyntax([])
        ))
    }

    /// `func name(to encoder: any Swift::Encoder) throws { body }`.
    private func encodeFunction(named name: String, modifiers: DeclModifierListSyntax, body: [CodeBlockItemSyntax.Item]) -> DeclSyntax {
        DeclSyntax(FunctionDeclSyntax(
            modifiers: modifiers,
            name: .identifier(name),
            signature: FunctionSignatureSyntax(
                parameterClause: FunctionParameterClauseSyntax([(label: "to", name: "encoder", type: .any(SwiftReference.swift("Encoder").type))]),
                effectSpecifiers: .throwing
            ),
            body: CodeBlockSyntax(body)
        ))
    }

    // MARK: - Properties

    /// The term type of a property, which carries its declared key and
    /// writes the triples the documents state about it.
    private func propertyTerm(_ property: PropertyDeclaration) -> DeclSyntax {
        DeclSyntax(StructDeclSyntax(
            leadingTrivia: documentation(property.node),
            attributes: deprecation(property.node),
            modifiers: .access(property.isPublic),
            name: .swift(property.termName),
            inheritanceClause: InheritanceClauseSyntax([SwiftReference.rdfCore("PropertyTerm").type]),
            memberBlock: MemberBlockSyntax(spaced: [
                DeclSyntax(VariableDeclSyntax(
                    leadingTrivia: .documentation(["The declared key of the property, from which an encoder derives its IRI."]),
                    modifiers: .publicStatic,
                    .let,
                    .identifier("key"),
                    value: key(property.node)
                )),
                initializer(documentation: ["The property's description."]),
                encodeFunction(named: "encode", modifiers: .public, body: description(of: property.node)),
            ])
        ))
    }

    /// `RDFCore::PropertyKey(key)`.
    private func propertyKey(_ key: some ExprSyntaxProtocol) -> ExprSyntax {
        SwiftReference.rdfCore("PropertyKey").expression.call(LabeledExprSyntax(expression: key))
    }

    /// `encoder.container(keyedBy: RDFCore::PropertyKey.self)`, or the
    /// decoder's.
    private func container(of coder: String) -> ExprSyntax {
        ExprSyntax.named(coder).member("container").call(LabeledExprSyntax("keyedBy", SwiftReference.rdfCore("PropertyKey").expression.dotSelf))
    }

    /// The value type that holds a property's values on an individual. It
    /// carries the property's declared key itself, as the term type does, so
    /// that it names no deprecated term type: every class whose members can
    /// have the property names it.
    private func propertyValue(_ property: PropertyDeclaration) -> DeclSyntax {
        let selfKey = propertyKey(ExprSyntax.keyword(.Self).member("key"))
        let values = type(of: property.kind)
        return DeclSyntax(StructDeclSyntax(
            leadingTrivia: .documentation(["The values an individual has for \(property.isPublic ? "``\(property.name)``" : "the property")."]),
            modifiers: .access(property.isPublic),
            name: .swift(property.valueName),
            inheritanceClause: InheritanceClauseSyntax([
                SwiftReference.rdfCore("PropertyValue").type,
                SwiftReference.swift("Decodable").type,
            ]),
            memberBlock: MemberBlockSyntax(spaced: [
                DeclSyntax(VariableDeclSyntax(
                    leadingTrivia: .documentation(["The declared key of the property, from which an encoder derives its IRI."]),
                    modifiers: .publicStatic,
                    .let,
                    .identifier("key"),
                    value: key(property.node)
                )),
                DeclSyntax(VariableDeclSyntax(
                    modifiers: .public,
                    .var,
                    .identifier("value"),
                    type: values,
                    value: .array([])
                )),
                DeclSyntax(InitializerDeclSyntax(
                    modifiers: .public,
                    signature: FunctionSignatureSyntax(parameterClause: FunctionParameterClauseSyntax([])),
                    body: CodeBlockSyntax([])
                )),
                DeclSyntax(InitializerDeclSyntax(
                    modifiers: .public,
                    signature: FunctionSignatureSyntax(
                        parameterClause: FunctionParameterClauseSyntax([(label: "from", name: "decoder", type: .any(SwiftReference.swift("Decoder").type))]),
                        effectSpecifiers: .throwing
                    ),
                    body: CodeBlockSyntax([
                        .decl(DeclSyntax(VariableDeclSyntax(.let, .identifier("container"), value: container(of: "decoder").tried))),
                        .expr(ExprSyntax.named("value").assigned(ExprSyntax.named("container").member("decode").call(
                            LabeledExprSyntax(expression: ExprSyntax.type(values).dotSelf),
                            LabeledExprSyntax("for", selfKey),
                            LabeledExprSyntax("as", decodingClass(property.kind))
                        ).tried)),
                    ])
                )),
                encodeFunction(named: "encode", modifiers: .public, body: [
                    .decl(DeclSyntax(VariableDeclSyntax(.var, .identifier("container"), value: container(of: "encoder")))),
                    .expr(ExprSyntax.named("container").member("encode").call(
                        LabeledExprSyntax(expression: ExprSyntax.named("value")),
                        LabeledExprSyntax("for", selfKey)
                    ).tried),
                ]),
            ])
        ))
    }

    /// The class a decoder makes a value of a property of `kind` a member
    /// of, when the document states no class for it: the class of the one
    /// class the property's range gives, else `rdfs:Resource`'s.
    private func decodingClass(_ kind: ValueKind) -> ExprSyntax {
        if case .individuals(let protocols) = kind, protocols.count == 1, let declaration = classDeclaration(protocols[0]) {
            return declaration.classReference.expression.dotSelf
        }
        return classDeclaration(.iri(.rdfsResource)).map { $0.classReference.expression.dotSelf } ?? .nil
    }

    /// The storing protocol that gives an individual a property's accessor,
    /// and the accessor, which keeps the value in the individual's storage.
    private func propertyStoring(_ property: PropertyDeclaration) -> [DeclSyntax] {
        let stored = ExprSyntax.named("storage").subscripted(ExprSyntax.named(property.valueName).dotSelf).member("value")
        func accessor(_ specifier: Keyword, _ statement: CodeBlockItemSyntax.Item) -> AccessorDeclSyntax {
            AccessorDeclSyntax(accessorSpecifier: .keyword(specifier), body: CodeBlockSyntax([statement]))
        }
        return [
            DeclSyntax(ProtocolDeclSyntax(
                leadingTrivia: .documentation(["An individual that has \(property.isPublic ? "``\(property.name)``" : "the property")."]),
                modifiers: .access(property.isPublic),
                name: .swift(property.storingName),
                inheritanceClause: InheritanceClauseSyntax([SwiftReference.rdfCore("PropertyValueStoring").type]),
                memberBlock: MemberBlockSyntax([])
            )),
            DeclSyntax(ExtensionDeclSyntax(
                extendedType: SwiftReference.local(property.storingName).type,
                memberBlock: MemberBlockSyntax([
                    DeclSyntax(VariableDeclSyntax(
                        leadingTrivia: documentation(property.node),
                        attributes: deprecation(property.node),
                        modifiers: property.isPublic ? .public : [],
                        .var,
                        .swift(property.member),
                        type: type(of: property.kind),
                        accessors: AccessorBlockSyntax(accessors: .accessors(AccessorDeclListSyntax([
                            accessor(.get, .expr(stored)),
                            accessor(.set, .expr(stored.assigned(ExprSyntax.named("newValue")))),
                            accessor(._modify, .stmt(StmtSyntax(YieldStmtSyntax(yieldedExpressions: .single(ExprSyntax(InOutExprSyntax(expression: stored))))))),
                        ])))
                    )),
                ])
            )),
        ]
    }

    /// The statements that write the triples the documents state about
    /// `node` to a keyed container of `encoder`.
    private func description(of node: SubjectTerm) -> [CodeBlockItemSyntax.Item] {
        let triples = layer.graph.filter { $0.subject == node }
        guard !triples.isEmpty else { return [.expr(ExprSyntax.discard.assigned(container(of: "encoder")))] }
        var predicates: [IRI] = []
        var objects: [IRI: [ObjectTerm]] = [:]
        for triple in triples {
            if objects[triple.predicate] == nil { predicates.append(triple.predicate) }
            objects[triple.predicate, default: []].append(triple.object)
        }
        let values = SwiftReference.rdfCore("Value").type
        return [.decl(DeclSyntax(VariableDeclSyntax(.var, .identifier("container"), value: container(of: "encoder"))))]
            + predicates.map { predicate in
                .expr(ExprSyntax.named("container").member("encode").call(
                    LabeledExprSyntax(expression: ExprSyntax.array(objects[predicate]!.map { expression($0, as: .values) }).as(.array(values))),
                    LabeledExprSyntax("for", propertyKey(predicate))
                ).tried)
            }
    }

    /// The coding key of a predicate's values: the declared key of the
    /// property, which its value type carries.
    private func propertyKey(_ predicate: IRI) -> ExprSyntax {
        if let declaration = propertyDeclaration(.iri(predicate)) {
            return propertyKey(declaration.valueReference.expression.member("key"))
        }
        return propertyKey(key(.iri(predicate)))
    }

    /// What these documents state about a resource a lower module declares.
    private func addition(_ node: SubjectTerm, index: Int) -> DeclSyntax {
        let subject = lower.class(node).map { ExprSyntax.implicitMember("class").call(LabeledExprSyntax(expression: $0.classReference.expression.dotSelf)) }
            ?? lower.property(node).map { ExprSyntax.implicitMember("property").call(LabeledExprSyntax(expression: $0.termReference.expression.dotSelf)) }
            ?? ExprSyntax.implicitMember("individual").call(LabeledExprSyntax(expression: lower.individual(node)!.reference.expression))
        return DeclSyntax(StructDeclSyntax(
            leadingTrivia: .documentation([
                "What \(layer.documents.joined(separator: " and ")) state\(layer.documents.count == 1 ? "s" : "") about \(node.iri?.rawValue ?? "a resource"), which a module below declares.",
            ]),
            attributes: deprecation(node),
            modifiers: .access(false),
            name: .swift(additionName(index)),
            inheritanceClause: InheritanceClauseSyntax([SwiftReference.rdfCore("Addition").type]),
            memberBlock: MemberBlockSyntax(spaced: [
                DeclSyntax(VariableDeclSyntax(.var, .identifier("resource"), type: SwiftReference.rdfCore("Value").type, accessors: .getter(subject))),
                encodeFunction(named: "encode", modifiers: [], body: description(of: node)),
            ])
        ))
    }

    private func additionName(_ index: Int) -> String {
        "addition \(index)"
    }

    // MARK: - References

    private func reference(_ storing: Storing) -> TypeSyntax {
        switch storing {
        case .class(let node): classDeclaration(node)!.storingReference.type
        case .property(let node): propertyDeclaration(node)!.storingReference.type
        }
    }

    private func classReference(_ instanceClass: InstanceClass) -> SwiftReference {
        switch instanceClass {
        case .class(let node): classDeclaration(node)!.classReference
        case .combination(let index): .local(declarations.combinations[index].name)
        }
    }

    /// The private constant holding an individual this module declares.
    private func handle(_ node: SubjectTerm) -> String {
        "resource \(declarations.order.firstIndex(of: node)!)"
    }

    /// An individual, as an expression: its private constant here, its
    /// public constant below.
    private func reference(_ node: SubjectTerm) -> ExprSyntax {
        if declarations.individuals[node] != nil { return .named(handle(node)) }
        return lower.individual(node)!.reference.expression
    }

    private func expression(_ value: ObjectTerm, as kind: ValueKind) -> ExprSyntax {
        func wrapped(_ form: String, _ expression: ExprSyntax) -> ExprSyntax {
            kind == .values ? ExprSyntax.implicitMember(form).call(LabeledExprSyntax(expression: expression)) : expression
        }
        switch value {
        case .literal(let literal):
            return wrapped("literal", literal.swiftExpression)
        case .iri, .blankNode, .tripleTerm:
            let node = value.node!
            if let declaration = classDeclaration(node) {
                return wrapped("class", declaration.classReference.expression.dotSelf)
            }
            if let declaration = propertyDeclaration(node) {
                return wrapped("property", declaration.termReference.expression.dotSelf)
            }
            return wrapped("individual", reference(node))
        }
    }

    /// The Swift type of a property's values.
    private func type(of kind: ValueKind) -> TypeSyntax {
        .array(memberType(of: kind))
    }

    private func memberType(of kind: ValueKind) -> TypeSyntax {
        switch kind {
        case .literals: SwiftReference.rdfCore("Literal").type
        case .classes: .any(.metatype(SwiftReference.rdfCore("ResourceClass").type))
        case .properties: .any(.metatype(SwiftReference.rdfCore("PropertyTerm").type))
        case .values: SwiftReference.rdfCore("Value").type
        case .individuals(let protocols): existential(protocols)
        }
    }

    /// `any A & B` of the public protocols among those of `classes`, or
    /// `any RDFCore::Resource` when none is.
    private func existential(_ classes: [SubjectTerm], publicOnly: Bool = false) -> TypeSyntax {
        let protocols = classes.compactMap(classDeclaration).filter { !publicOnly || $0.isPublic }.map(\.protocolReference.type)
        return .any(protocols.isEmpty ? SwiftReference.rdfCore("Resource").type : .composition(protocols))
    }

    /// The Swift type of an individual's public constant.
    private func publicType(_ type: IndividualType) -> TypeSyntax {
        switch type {
        case .existential(let classes): existential(classes, publicOnly: true)
        case .individualClass(let node): classDeclaration(node)!.classReference.type
        case .storing(let node): .any(classDeclaration(node)!.storingReference.type)
        }
    }

    // MARK: - Documentation

    /// DocC documentation from `rdfs:label` and `rdfs:comment`.
    private func documentation(_ node: SubjectTerm) -> Trivia {
        var paragraphs: [[String]] = []
        for literal in vocabulary.literals(.rdfsLabel, of: node) + vocabulary.literals(.rdfsComment, of: node) {
            var lines = literal.lexicalForm.split(separator: "\n", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespaces) }
            while lines.first?.isEmpty == true { lines.removeFirst() }
            while lines.last?.isEmpty == true { lines.removeLast() }
            if !lines.isEmpty { paragraphs.append(lines) }
        }
        return .documentation(Array(paragraphs.joined(separator: [""])))
    }

    /// `@available(*, deprecated)` from `owl:deprecated true`, on the Swift
    /// of a deprecated resource and of one that names it (``Deprecations``).
    private func deprecation(_ node: SubjectTerm) -> AttributeListSyntax {
        Deprecations.attributes(deprecations.contains(node))
    }
}
