import Foundation
import IRIKit
import RDFCore

/// The Swift source of one module: the things its documents describe.
///
/// See ``Declarations`` for what each resource becomes. Besides them:
///
/// - `rdfs:label` and `rdfs:comment` are the declarations' documentation,
///   and `owl:deprecated true` is `@available(*, deprecated)`.
/// - Each individual's values are set once, the first time any individual
///   of the module is read, since individuals refer to each other, cycles
///   included (`:alice foaf:knows :bob . :bob foaf:knows :alice .`).
/// - A property's term type writes what the documents state about the
///   property, as a class's Swift class writes its class's description; a
///   property is never a module-level value.
/// - `ontology` is every description the documents give, the way back to
///   RDF.
/// - Every declaration of another module, and every public one of this
///   module, is named with a module selector (SE-0491), `RDF::Property`,
///   which looks only in that module. A module may name a resource like a
///   module it imports: the entailment regimes' `ent:RDF` is the constant
///   `RDF` in a module that imports `RDF`, and would hide that module from
///   `RDF.Property`.
///
/// The generated Swift keeps every individual's values in its
/// ``RDFCore/IndividualStorage``, the storage `@Ontology` uses too, so a
/// translated individual and one declared in the DSL are the same kind of
/// ``RDFCore/Resource``.
struct SwiftSource: DeclarationScope {
    let layer: Layer
    let vocabulary: Vocabulary
    let declarations: Declarations
    let below: [Declarations]
    let lower: Lower

    /// The nodes whose Swift is `@available(*, deprecated)`.
    private var deprecations = Deprecations()

    init(layer: Layer, vocabulary: Vocabulary, declarations: Declarations, below: [Declarations]) {
        self.layer = layer
        self.vocabulary = vocabulary
        self.declarations = declarations
        self.below = below
        self.lower = Lower(below)
        self.deprecations = Deprecations(self, vocabulary)
    }

    func render() -> String {
        var source = """
            // Generated by RDFTranslator from \(layer.documents.isEmpty ? "no documents" : layer.documents.joined(separator: ", ")).
            // Edit the RDF and build again; this file is rewritten on every build.

            import IRIKit
            import RDFCore

            """
        for module in below.map(\.module) {
            source += "import \(module)\n"
        }
        source += "\n" + namespaceTypes()

        for node in declarations.order {
            if let declaration = declarations.classes[node] {
                source += "\n" + classProtocol(declaration)
                source += "\n" + storingProtocol(declaration)
                source += "\n" + individualClass(of: declaration)
            }
            if let property = declarations.properties[node] {
                source += "\n" + propertyTerm(property)
                source += "\n" + propertyValue(property)
                source += "\n" + propertyStoring(property)
            }
        }
        // A combination class is generated only for the blank nodes that
        // are its instances; a named individual's own class conforms to the
        // same storing protocols instead.
        let instantiated = Set(declarations.order.compactMap { node -> Int? in
            guard node.iri == nil, case .combination(let index)? = declarations.individuals[node]?.instanceOf else { return nil }
            return index
        })
        for (index, combination) in declarations.combinations.enumerated() where instantiated.contains(index) {
            source += "\n" + combinationClass(combination)
        }

        // The individuals, each an instance of its class, and the values the
        // documents give them. A named individual is the one instance of a
        // Swift class of its own, which carries its declared key.
        for node in declarations.order {
            guard let individual = declarations.individuals[node], node.iri != nil else { continue }
            source += "\n" + namedIndividualClass(node, individual)
        }
        source += "\n"
        for node in declarations.order {
            guard let individual = declarations.individuals[node] else { continue }
            let type = node.iri == nil ? classReference(individual.instanceOf) : namedIndividualClassName(node)
            source += deprecation(node) + "private let \(handle(node)) = \(type)()\n"
        }

        for node in declarations.order {
            guard let individual = declarations.individuals[node], individual.isPublic else { continue }
            source += "\n" + docComment(node) + deprecation(node)
            source += "public let \(individual.name.swiftIdentifier): \(individual.publicType) = { _ = described; return \(handle(node)) }()\n"
        }

        // `rdf:type` is the property every member of `rdfs:Resource` writes
        // its classes with, so the module that declares `rdfs:Resource`
        // gives it to the class's storing protocol.
        if let resource = declarations.classes[.iri(.rdfsResource)], let type = propertyDeclaration(.iri(.rdfType)) {
            source += "\n/// `rdf:type`, the property a member of `rdfs:Resource` writes its classes with.\n"
            source += "extension \(resource.storingReference) {\n"
            source += "    public static var typeProperty: RDFCore::TermKey? { \(type.termReference).key }\n}\n"
        }

        for (index, node) in declarations.additions.enumerated() {
            source += "\n" + addition(node, index: index)
        }
        return source + documents()
    }

    /// The values the documents give the individuals and the descriptions
    /// they give, which name every declaration of the module, deprecated
    /// ones included. Swift warns where a declaration that is not deprecated
    /// names a deprecated one, so they are named in deprecated members of a
    /// private type, and `described` and `ontology` reach those members
    /// through the requirements of a protocol, which are not deprecated.
    private func documents() -> String {
        var source = """

            /// What the documents give the individuals and the descriptions they give.
            private protocol `what the documents state` {
                /// Sets the values the documents give the individuals, once.
                static var described: Swift::Void { get }

                /// The descriptions the documents give.
                static var ontology: [any RDFCore::Description] { get }
            }

            /// Names every declaration of the module, deprecated ones included, without a warning.
            private struct `the documents`: `what the documents state` {
                @available(*, deprecated)
                static let described: Swift::Void = {

            """
        for node in declarations.order where declarations.individuals[node] != nil {
            for (property, objects) in values(of: node) {
                let declaration = propertyDeclaration(property)!
                source += "        \(handle(node)).\(declaration.member.swiftIdentifier) = [\(objects.map { expression($0, as: declaration.kind) }.joined(separator: ", "))]\n"
            }
        }
        source += "    }()\n\n"

        let subjects = Set(layer.graph.map(\.subject))
        var entries: [String] = []
        for node in declarations.order where subjects.contains(node) {
            if let declaration = declarations.classes[node] {
                entries.append("RDFCore::ClassDescription(\(declaration.classReference).self)")
            } else if let property = declarations.properties[node] {
                entries.append("\(property.termReference)()")
            } else {
                entries.append(handle(node))
            }
        }
        entries += declarations.additions.indices.map { "\(additionName($0))()" }
        source += "    @available(*, deprecated)\n"
        source += "    static var ontology: [any RDFCore::Description] {\n        ["
        source += entries.map { "\n            \($0)," }.joined()
        source += entries.isEmpty ? "]\n" : "\n        ]\n"
        source += "    }\n}\n\n"
        source += "/// Sets the values the documents give the individuals, once.\n"
        source += "private let described: Swift::Void = (`the documents`.self as any `what the documents state`.Type).described\n"

        let describers = layer.documents.isEmpty ? "this module's documents" : layer.documents.joined(separator: " and ")
        source += """

            /// The descriptions \(describers) give\(layer.documents.count == 1 ? "s" : "").
            ///
            /// Encoding them gives back the documents' graph:
            ///
            ///     let document = try NTriplesEncoder().encode(ontology)
            public let ontology: [any RDFCore::Description] = {
                _ = described
                return (`the documents`.self as any `what the documents state`.Type).ontology
            }()

            """
        return source
    }

    // MARK: - Classes

    private func access(_ isPublic: Bool) -> String {
        isPublic ? "public " : "private "
    }

    private func classProtocol(_ declaration: ClassDeclaration) -> String {
        let refined = (declarations.refinements[declaration.node] ?? []).compactMap(classDeclaration).map(\.protocolReference)
        var text = docComment(declaration.node) + deprecation(declaration.node)
        text += "\(access(declaration.isPublic))protocol \(declaration.protocolName.swiftIdentifier): \(refined.isEmpty ? "RDFCore::Resource" : refined.joined(separator: ", ")) {"
        let requirements = (declarations.requirements[declaration.node] ?? []).compactMap(propertyDeclaration)
        if requirements.isEmpty { return text + "}\n" }
        text += "\n"
        for requirement in requirements {
            text += docComment(requirement.node, indent: "    ") + deprecation(requirement.node, indent: "    ")
            text += "    var \(requirement.member.swiftIdentifier): \(type(of: requirement.kind)) { get set }\n"
        }
        return text + "}\n"
    }

    /// The storing protocol of a class, which gives a member of the class
    /// every property it can have, each through its own storing protocol.
    private func storingProtocol(_ declaration: ClassDeclaration) -> String {
        let refined = [declaration.protocolReference] + declaration.storing.map(reference)
        var text = "/// A member of ``\(declaration.isPublic ? declaration.protocolName : "")`` that keeps its property values in an ``RDFCore/IndividualStorage``.\n"
        if !declaration.isPublic { text = "/// A member of the class that keeps its property values in an ``RDFCore/IndividualStorage``.\n" }
        text += deprecation(declaration.node)
        text += "\(access(declaration.isPublic))protocol \(declaration.storingName.swiftIdentifier): \(refined.joined(separator: ", ")) {}\n"
        return text
    }

    /// The final class whose instances are the members of an RDF class. Its
    /// type is the class itself, a resource, so it writes the class's
    /// description too.
    private func individualClass(of declaration: ClassDeclaration) -> String {
        let access = self.access(declaration.isPublic)
        var text = docComment(declaration.node) + deprecation(declaration.node)
        text += "\(access)final class \(declaration.className.swiftIdentifier): \(declaration.storingReference), RDFCore::ResourceClass, RDFCore::DecodableResource {\n"
        text += "    public static let classKey: RDFCore::TermKey? = \(key(declaration.node))\n\n"
        text += "    /// A member of the class as a property value.\n"
        text += "    public typealias Member = \(memberType(of: declaration.member))\n\n"
        let properties = declaration.stored.sorted(by: SubjectTerm.inIRIOrder).compactMap(propertyDeclaration).map { "\($0.valueReference).self" }
        text += "    /// The properties a member of the class has, which a decoder reads.\n"
        text += "    public static let properties: [any (RDFCore::PropertyValue & Swift::Decodable).Type] = [\(properties.joined(separator: ", "))]\n\n"
        text += individual(stated: [declaration.node])
        text += "\n    public static func encodeDescription(to encoder: any Swift::Encoder) throws {\n"
        text += description(of: declaration.node, indent: "        ")
        text += "    }\n}\n"
        return text
    }

    private func combinationClass(_ combination: Combination) -> String {
        let conformances = combination.storing.map(reference)
        var text = "/// An individual that is a member of \(combination.stated.isEmpty ? "no stated class" : "several classes"), or has properties its class's members cannot have.\n"
        text += Deprecations.attribute(deprecations.contains(combination))
        text += "private final class \(combination.name.swiftIdentifier): \(conformances.isEmpty ? "RDFCore::PropertyValueStoring" : (conformances + ["RDFCore::PropertyValueStoring"]).joined(separator: ", ")) {\n"
        text += individual(stated: combination.stated)
        return text + "}\n"
    }

    /// The Swift class of a named individual, whose one instance is the
    /// individual, and whose declared key names it at the boundary.
    private func namedIndividualClass(_ node: SubjectTerm, _ declaration: IndividualDeclaration) -> String {
        let stated: [SubjectTerm]
        var conformances: [String]
        switch declaration.instanceOf {
        case .class(let type):
            stated = [type]
            conformances = [classDeclaration(type)!.storingReference]
        case .combination(let index):
            let combination = declarations.combinations[index]
            stated = combination.stated
            conformances = combination.storing.map(reference) + ["RDFCore::PropertyValueStoring"]
        }
        var text = "/// The class of \(node.iri!.rawValue), a named individual.\n" + deprecation(node)
        text += "private final class \(namedIndividualClassName(node)): \(conformances.joined(separator: ", ")) {\n"
        text += "    static let key: RDFCore::TermKey? = \(key(node))\n\n"
        text += individual(stated: stated)
        return text + "}\n"
    }

    private func namedIndividualClassName(_ node: SubjectTerm) -> String {
        ("resource \(declarations.order.firstIndex(of: node)!) Individual").swiftIdentifier
    }

    // MARK: - Keys

    /// The namespaces of the IRIs this module declares, and of the
    /// predicates its documents use that no module declares as a property,
    /// each a ``RDFCore/Vocabulary`` that the declared keys refer to. Two
    /// namespaces are one only when their Unicode scalars are the same:
    /// Swift's `==` on `String` would make a precomposed `é` and `e` with
    /// U+0301 one namespace, and so give two IRIs one key.
    private var namespaces: [String] {
        var namespaces: [String] = []
        let undeclared = layer.graph.map { SubjectTerm.iri($0.predicate) }.filter { propertyDeclaration($0) == nil }
        for node in declarations.order + undeclared {
            guard let namespace = node.iri?.namespace else { continue }
            if namespaces.firstIndex(ofScalars: namespace) == nil { namespaces.append(namespace) }
        }
        return namespaces
    }

    private func namespaceTypes() -> String {
        namespaces.enumerated().map { index, namespace in
            "/// The namespace \(namespace), which declared keys of this module refer to.\n"
                + "private struct \(("namespace \(index)").swiftIdentifier): RDFCore::Vocabulary {\n"
                + "    static let namespace = \(namespace.swiftStringLiteral)\n}\n"
        }.joined(separator: "\n")
    }

    /// The declared key of a node: its local name in its namespace, or `nil`
    /// for a blank node.
    private func key(_ node: SubjectTerm) -> String {
        guard let iri = node.iri else { return "nil" }
        let index = namespaces.firstIndex(ofScalars: iri.namespace)!
        return "RDFCore::TermKey(\(iri.localName.swiftStringLiteral), in: \(("namespace \(index)").swiftIdentifier).self)"
    }

    /// The classes and the storage of a generated class. Its
    /// `Encodable` conformance comes from ``RDFCore/PropertyValueStoring``,
    /// which writes the classes as `rdf:type`.
    private func individual(stated: [SubjectTerm]) -> String {
        let types = stated.compactMap(classDeclaration).map { "\($0.classReference).self" }
        var text = "    public static let classes: [any RDFCore::ResourceClass.Type] = [\(types.joined(separator: ", "))]\n\n"
        text += "    public let storage = RDFCore::IndividualStorage()\n\n"
        text += "    /// An individual no declaration names: a blank node at the boundary.\n"
        text += "    public init() {}\n"
        return text
    }

    // MARK: - Properties

    /// The term type of a property, which carries its declared key and
    /// writes the triples the documents state about it.
    private func propertyTerm(_ property: PropertyDeclaration) -> String {
        var text = docComment(property.node) + deprecation(property.node)
        text += "\(access(property.isPublic))struct \(property.termName.swiftIdentifier): RDFCore::PropertyTerm {\n"
        text += "    /// The declared key of the property, from which an encoder derives its IRI.\n"
        text += "    public static let key = \(key(property.node))\n\n"
        text += "    /// The property's description.\n"
        text += "    public init() {}\n\n"
        text += "    public func encode(to encoder: any Swift::Encoder) throws {\n"
        text += description(of: property.node, indent: "        ")
        text += "    }\n}\n"
        return text
    }

    /// The value type that holds a property's values on an individual. It
    /// carries the property's declared key itself, as the term type does, so
    /// that it names no deprecated term type: every class whose members can
    /// have the property names it.
    private func propertyValue(_ property: PropertyDeclaration) -> String {
        let access = self.access(property.isPublic)
        var text = "/// The values an individual has for \(property.isPublic ? "``\(property.name)``" : "the property").\n"
        text += "\(access)struct \(property.valueName.swiftIdentifier): RDFCore::PropertyValue, Swift::Decodable {\n"
        text += "    /// The declared key of the property, from which an encoder derives its IRI.\n"
        text += "    public static let key = \(key(property.node))\n\n"
        text += "    public var value: \(type(of: property.kind)) = []\n\n"
        text += "    public init() {}\n\n"
        text += "    public init(from decoder: any Swift::Decoder) throws {\n"
        text += "        let container = try decoder.container(keyedBy: RDFCore::PropertyKey.self)\n"
        text += "        value = try container.decode(\(type(of: property.kind)).self, for: RDFCore::PropertyKey(Self.key)\(decodingClass(property.kind)))\n"
        text += "    }\n\n"
        text += "    public func encode(to encoder: any Swift::Encoder) throws {\n"
        text += "        var container = encoder.container(keyedBy: RDFCore::PropertyKey.self)\n"
        text += "        try container.encode(value, for: RDFCore::PropertyKey(Self.key))\n"
        text += "    }\n}\n"
        return text
    }

    /// The class a decoder makes a value of a property of `kind` a member
    /// of, when the document states no class for it: the class of the one
    /// class the property's range gives, else `rdfs:Resource`'s.
    private func decodingClass(_ kind: ValueKind) -> String {
        if case .individuals(let protocols) = kind, protocols.count == 1, let declaration = classDeclaration(protocols[0]) {
            return ", as: \(declaration.classReference).self"
        }
        return ", as: " + (classDeclaration(.iri(.rdfsResource)).map { "\($0.classReference).self" } ?? "nil")
    }

    /// The storing protocol that gives an individual a property's accessor.
    private func propertyStoring(_ property: PropertyDeclaration) -> String {
        let access = self.access(property.isPublic)
        let member = property.member.swiftIdentifier
        let value = property.valueName.swiftIdentifier
        var text = "/// An individual that has \(property.isPublic ? "``\(property.name)``" : "the property").\n"
        text += "\(access)protocol \(property.storingName.swiftIdentifier): RDFCore::PropertyValueStoring {}\n\n"
        text += "extension \(property.storingName.swiftIdentifier) {\n"
        text += docComment(property.node, indent: "    ") + deprecation(property.node, indent: "    ")
        text += "    \(property.isPublic ? "public " : "")var \(member): \(type(of: property.kind)) {\n"
        text += "        get { storage[\(value).self].value }\n"
        text += "        set { storage[\(value).self].value = newValue }\n"
        text += "        _modify { yield &storage[\(value).self].value }\n"
        text += "    }\n}\n"
        return text
    }

    /// Writes the triples the documents state about `node` to a keyed
    /// container of `encoder`.
    private func description(of node: SubjectTerm, indent: String) -> String {
        let triples = layer.graph.filter { $0.subject == node }
        let container = "encoder.container(keyedBy: RDFCore::PropertyKey.self)"
        guard !triples.isEmpty else { return "\(indent)_ = \(container)\n" }
        var text = "\(indent)var container = \(container)\n"
        var predicates: [IRI] = []
        var objects: [IRI: [ObjectTerm]] = [:]
        for triple in triples {
            if objects[triple.predicate] == nil { predicates.append(triple.predicate) }
            objects[triple.predicate, default: []].append(triple.object)
        }
        for predicate in predicates {
            let values = objects[predicate]!.map { expression($0, as: .values) }
            text += "\(indent)try container.encode([\(values.joined(separator: ", "))] as [RDFCore::Value], for: \(propertyKey(predicate)))\n"
        }
        return text
    }

    /// The coding key of a predicate's values: the declared key of the
    /// property, which its value type carries.
    private func propertyKey(_ predicate: IRI) -> String {
        if let declaration = propertyDeclaration(.iri(predicate)) {
            return "RDFCore::PropertyKey(\(declaration.valueReference).key)"
        }
        return "RDFCore::PropertyKey(\(key(.iri(predicate))))"
    }

    /// What these documents state about a resource a lower module declares.
    private func addition(_ node: SubjectTerm, index: Int) -> String {
        let subject = lower.class(node).map { ".class(\($0.classReference).self)" }
            ?? lower.property(node).map { ".property(\($0.termReference).self)" }
            ?? ".individual(\(lower.individual(node)!.reference))"
        var text = "/// What \(layer.documents.joined(separator: " and ")) state\(layer.documents.count == 1 ? "s" : "") about \(node.iri?.rawValue ?? "a resource"), which a module below declares.\n"
        text += deprecation(node) + "private struct \(additionName(index)): RDFCore::Addition {\n"
        text += "    var resource: RDFCore::Value { \(subject) }\n\n"
        text += "    func encode(to encoder: any Swift::Encoder) throws {\n"
        text += description(of: node, indent: "        ")
        text += "    }\n}\n"
        return text
    }

    private func additionName(_ index: Int) -> String {
        ("addition \(index)").swiftIdentifier
    }

    // MARK: - References

    private func reference(_ storing: Storing) -> String {
        switch storing {
        case .class(let node): classDeclaration(node)!.storingReference
        case .property(let node): propertyDeclaration(node)!.storingReference
        }
    }

    private func classReference(_ instanceClass: InstanceClass) -> String {
        switch instanceClass {
        case .class(let node): classDeclaration(node)!.classReference
        case .combination(let index): declarations.combinations[index].name.swiftIdentifier
        }
    }

    /// The private constant holding an individual this module declares.
    private func handle(_ node: SubjectTerm) -> String {
        ("resource \(declarations.order.firstIndex(of: node)!)").swiftIdentifier
    }

    /// An individual, as an expression: its private constant here, its
    /// public constant below.
    private func reference(_ node: SubjectTerm) -> String {
        if declarations.individuals[node] != nil { return handle(node) }
        return lower.individual(node)!.reference
    }

    private func expression(_ value: ObjectTerm, as kind: ValueKind) -> String {
        switch value {
        case .literal(let literal):
            return kind == .values ? ".literal(\(literal.swiftExpression))" : literal.swiftExpression
        case .iri, .blankNode, .tripleTerm:
            let node = value.node!
            if let declaration = classDeclaration(node) {
                return kind == .values ? ".class(\(declaration.classReference).self)" : "\(declaration.classReference).self"
            }
            if let declaration = propertyDeclaration(node) {
                return kind == .values ? ".property(\(declaration.termReference).self)" : "\(declaration.termReference).self"
            }
            return kind == .values ? ".individual(\(reference(node)))" : reference(node)
        }
    }

    private func type(of kind: ValueKind) -> String {
        "[" + memberType(of: kind) + "]"
    }

    private func memberType(of kind: ValueKind) -> String {
        switch kind {
        case .literals: "RDFCore::Literal"
        case .classes: "any RDFCore::ResourceClass.Type"
        case .properties: "any RDFCore::PropertyTerm.Type"
        case .values: "RDFCore::Value"
        case .individuals(let protocols):
            "any " + (protocols.isEmpty ? "RDFCore::Resource" : protocols.compactMap(classDeclaration).map(\.protocolReference).joined(separator: " & "))
        }
    }

    // MARK: - Documentation

    /// DocC documentation from `rdfs:label` and `rdfs:comment`.
    private func docComment(_ node: SubjectTerm, indent: String = "") -> String {
        var paragraphs: [[String]] = []
        for literal in vocabulary.literals(.rdfsLabel, of: node) + vocabulary.literals(.rdfsComment, of: node) {
            var lines = literal.lexicalForm.split(separator: "\n", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespaces) }
            while lines.first?.isEmpty == true { lines.removeFirst() }
            while lines.last?.isEmpty == true { lines.removeLast() }
            if !lines.isEmpty { paragraphs.append(lines) }
        }
        let text = paragraphs.map { lines in lines.map { indent + ($0.isEmpty ? "///" : "/// " + $0) }.joined(separator: "\n") }
            .joined(separator: "\n\(indent)///\n")
        return text.isEmpty ? "" : text + "\n"
    }

    /// `@available(*, deprecated)` from `owl:deprecated true`, on the Swift
    /// of a deprecated resource and of one that names it (``Deprecations``).
    private func deprecation(_ node: SubjectTerm, indent: String = "") -> String {
        Deprecations.attribute(deprecations.contains(node), indent: indent)
    }
}
