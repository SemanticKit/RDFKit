import Foundation
import RDFCore

/// The Swift source of one module: the things its documents describe.
///
/// - Each class is a protocol, refining the protocols of its superclasses.
/// - Each resource is one object of a class of its own, conforming to the
///   protocols of every class it is a member of, stated or entailed.
///   A resource the documents describe that is not a class is a public
///   value named by its local name.
/// - Each property is a member of the protocol of its domain, typed by its
///   range. A property whose domain is `owl:Thing`, `rdfs:Resource`, a class
///   with no Swift protocol, or none, is a member of every ``Resource``.
/// - `rdfs:label` and `rdfs:comment` are the declarations' documentation,
///   and `owl:deprecated true` is `@available(*, deprecated)`.
/// - `ontology` is every resource the documents describe, the way back to
///   RDF.
struct SwiftSource {
    let layer: Layer
    let vocabulary: Vocabulary
    let declarations: Declarations
    let below: [Declarations]

    private var all: [Declarations] { below + [declarations] }

    func render() -> String {
        let locals = localResources()
        var handles: [NodeID: String] = [:]
        for (index, node) in locals.enumerated() {
            handles[node] = SwiftName.identifier("resource \(index)")
        }
        func reference(_ node: NodeID) -> String {
            belowValue(node) ?? handles[node]!
        }

        var source = """
            // Generated by RDFTranslator from \(layer.documents.isEmpty ? "no documents" : layer.documents.joined(separator: ", ")).
            // Edit the RDF and build again; this file is rewritten on every build.

            import IRIKit
            import RDFCore
            import RDFRuntime

            """
        for module in below.map(\.module) {
            source += "import \(module)\n"
        }

        // Classes.
        for node in declarations.order {
            guard let name = declarations.protocols[node] else { continue }
            let refined = (declarations.refinements[node] ?? []).compactMap(protocolName)
            source += "\n" + documentation(node)
            source += "public protocol \(SwiftName.identifier(name)): \(refined.isEmpty ? "RDFRuntime.Resource" : refined.joined(separator: ", ")) {}\n"
        }

        // Properties.
        for node in declarations.order {
            guard let name = declarations.values[node], vocabulary.isProperty(node), name != "propertyValues" else { continue }
            source += "\n" + member(node, name: name, handle: handles[node]!)
        }

        // Resources the documents describe that are not classes.
        for node in declarations.order {
            guard let name = declarations.values[node] else { continue }
            source += "\n" + documentation(node)
            source += "public let \(SwiftName.identifier(name)): \(publicType(node)) = \(handles[node]!)\n"
        }

        let describers = layer.documents.isEmpty ? "this module's documents" : layer.documents.joined(separator: " and ")
        let described = locals.filter { node in layer.statements.contains { $0.subject == node } }
        source += """

            /// The resources \(describers) describe\(layer.documents.count == 1 ? "s" : "").
            ///
            /// Encoding them gives back the documents' graph:
            ///
            ///     let document = try NTriplesEncoder().encode(ontology)
            public let ontology: [any RDFRuntime.Resource] = [
            """
        source += described.map { "\n    \(handles[$0]!)," }.joined()
        source += described.isEmpty ? "]\n" : "\n]\n"

        // One object for every resource the documents name.
        for node in locals {
            let conformances = conformances(node)
            source += """

                private let \(handles[node]!): \(publicType(node)) = {
                    final class Node: \(conformances.isEmpty ? "RDFRuntime.Resource" : conformances.joined(separator: ", ")) {
                        static var iri: IRIKit.IRI? { \(node.iri.map(SwiftName.stringLiteral) ?? "nil") }
                        let propertyValues = RDFRuntime.PropertyValues {
                            var values: [RDFRuntime.PropertyValues.Statement] = []

                """
            for statement in layer.statements where statement.subject == node {
                let object: String
                switch statement.object {
                case .node(let node): object = reference(node)
                case .literal(let literal): object = Self.expression(literal)
                }
                source += "            values.append((\(reference(.iri(statement.predicate))), \(object)))\n"
            }
            source += """
                            return values
                        }
                    }
                    return Node()
                }()

                """
        }
        return source
    }

    // MARK: - Resources

    /// Every node the documents name, except the values of lower layers,
    /// which keep their objects. A subject a lower layer declares gets an
    /// object here too, to carry what these documents add about it.
    private func localResources() -> [NodeID] {
        var seen: Set<NodeID> = []
        var nodes: [NodeID] = []
        func add(_ node: NodeID, subject: Bool) {
            guard subject || belowValue(node) == nil, seen.insert(node).inserted else { return }
            nodes.append(node)
        }
        for statement in layer.statements {
            add(statement.subject, subject: true)
            add(.iri(statement.predicate), subject: false)
            if let object = statement.object.node { add(object, subject: false) }
        }
        return nodes
    }

    private func belowValue(_ node: NodeID) -> String? {
        for declarations in below {
            if let name = declarations.values[node] {
                return "\(declarations.module).\(SwiftName.identifier(name))"
            }
        }
        return nil
    }

    private func protocolName(_ node: NodeID) -> String? {
        for declarations in all {
            if let name = declarations.protocols[node] {
                return "\(declarations.module).\(SwiftName.identifier(name))"
            }
        }
        return nil
    }

    /// The protocols of every class the resource is a member of.
    private func conformances(_ node: NodeID) -> [String] {
        vocabulary.classes(of: node).compactMap(protocolName).sorted()
    }

    /// The type of the resource's value: the protocols of the classes the
    /// documents state it is a member of, without those another implies.
    private func publicType(_ node: NodeID) -> String {
        let stated = Set(vocabulary.statements.compactMap { statement -> NodeID? in
            guard statement.subject == node, statement.predicate == Term.type,
                  let type = statement.object.node, protocolName(type) != nil else { return nil }
            return type
        })
        let minimal = stated.filter { type in
            !stated.contains { other in other != type && refinementClosure(of: other).contains(type) }
        }
        let names = minimal.compactMap(protocolName).sorted()
        return "any " + (names.isEmpty ? "RDFRuntime.Resource" : names.joined(separator: " & "))
    }

    private func refinementClosure(of node: NodeID) -> Set<NodeID> {
        declarations.refinementClosure(of: node, below: below)
    }

    // MARK: - Properties

    private func member(_ node: NodeID, name: String, handle: String) -> String {
        let everything: Set<NodeID> = [.iri(Term.thing), .iri(Term.resource)]
        let domains = vocabulary.domains(of: node).filter { !everything.contains($0) }.compactMap(protocolName)
        let extended: String
        if let first = domains.first {
            let others = Array(Set(domains.dropFirst()).subtracting([first])).sorted()
            extended = first + (others.isEmpty ? "" : " where Self: " + others.joined(separator: " & "))
        } else {
            extended = "RDFRuntime.Resource"
        }

        let ranges = vocabulary.ranges(of: node)
        let type: String
        let read: String
        if ranges.contains(where: vocabulary.isLiteralClass) {
            type = "[RDFCore.Literal]"
            read = ".compactMap { $0 as? RDFCore.Literal }"
        } else {
            let classes = Array(Set(ranges.filter { $0 != .iri(Term.resource) }.compactMap(protocolName))).sorted()
            if classes.isEmpty {
                type = "[RDFRuntime.PropertyValues.Value]"
                read = ""
            } else {
                let element = "any " + classes.joined(separator: " & ")
                type = "[\(element)]"
                read = ".compactMap { $0 as? \(element) }"
            }
        }
        return "extension \(extended) {\n"
            + documentation(node, indent: "    ")
            + "    public var \(SwiftName.identifier(name)): \(type) {\n"
            + "        get { propertyValues.values(of: \(handle))\(read) }\n"
            + "        set { propertyValues.replace(\(handle), with: newValue) }\n"
            + "    }\n"
            + "}\n"
    }

    // MARK: - Documentation

    /// DocC documentation from `rdfs:label` and `rdfs:comment`, and
    /// `@available(*, deprecated)` from `owl:deprecated true`.
    private func documentation(_ node: NodeID, indent: String = "") -> String {
        var paragraphs: [[String]] = []
        for literal in vocabulary.literals(Term.label, of: node) + vocabulary.literals(Term.comment, of: node) {
            var lines = literal.lexicalForm.split(separator: "\n", omittingEmptySubsequences: false)
                .map { $0.trimmingCharacters(in: .whitespaces) }
            while lines.first?.isEmpty == true { lines.removeFirst() }
            while lines.last?.isEmpty == true { lines.removeLast() }
            if !lines.isEmpty { paragraphs.append(lines) }
        }
        var text = paragraphs.map { lines in lines.map { indent + ($0.isEmpty ? "///" : "/// " + $0) }.joined(separator: "\n") }
            .joined(separator: "\n\(indent)///\n")
        if !text.isEmpty { text += "\n" }
        if vocabulary.isDeprecated(node) {
            text += indent + "@available(*, deprecated)\n"
        }
        return text
    }

    // MARK: - Literals

    static func expression(_ literal: Literal) -> String {
        let lexical = SwiftName.stringLiteral(literal.lexicalForm)
        if let language = literal.languageTag {
            var arguments = [lexical, "languageTag: \(SwiftName.stringLiteral(language))"]
            if let direction = literal.baseDirection { arguments.append("baseDirection: .\(direction.rawValue)") }
            return "try! RDFCore.Literal(\(arguments.joined(separator: ", ")))"
        }
        if let datatype = literal.datatype {
            return "try! RDFCore.Literal(\(lexical), datatype: \(SwiftName.stringLiteral(datatype.rawValue)))"
        }
        return "RDFCore.Literal(\(lexical))"
    }
}
